def _gsettings_scheme():
    """GNOME/freedesktop color-scheme via gsettings -> 'dark'|'light'|None.

    Best-effort and fast (short timeout); never raises.  darkdetect already
    reads this on most desktops, but we probe directly as a fallback for the
    org.freedesktop.appearance signal the OS shell publishes.
    """
    try:
        import subprocess
        out = subprocess.run(
            ["gsettings", "get", "org.gnome.desktop.interface", "color-scheme"],
            capture_output=True, text=True, timeout=1.5)
        val = (out.stdout or "").strip().strip("'\"").lower()
        if "dark" in val:
            return "dark"
        if "light" in val or "default" in val:
            return "light"
    except Exception:
        pass
    return None


def _system_theme():
    """Best-effort OS appearance preference -> 'light' | 'dark'.

    Order: darkdetect (honours org.freedesktop.appearance + the GNOME
    color-scheme gsettings key on Linux, the registry on Windows, the defaults
    domain on macOS), then a direct gsettings probe, then a safe 'dark'
    default.  Never raises; safe under Xvfb / headless CI.
    """
    try:
        if darkdetect is not None:
            t = darkdetect.theme()           # 'Dark' | 'Light' | None
            if t:
                return "dark" if str(t).lower().startswith("d") else "light"
    except Exception:
        pass
    g = _gsettings_scheme()
    if g:
        return g
    return "dark"


def _resolve_theme(theme):
    """Map a requested theme to a concrete 'light'/'dark'.

    Explicit ``"light"``/``"dark"`` are honoured verbatim — that is an app's
    persisted user override.  Anything else (``"system"``, ``None``, ``""``,
    unknown) FOLLOWS the OS appearance.  This is why apps default to the
    system Aura Dark/Light and re-theme with the desktop.
    """
    if theme in ("light", "dark"):
        return theme
    return _system_theme()


