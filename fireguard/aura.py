    # ---- theme ---------------------------------------------------------
    def _on_toggle_theme(self):
        self.set_theme("dark" if self._theme_switch.get() else "light")

    def configure(self, cnf=None, **kw):
        """Intercept ``config(menu=...)``: the native menubar strip is drawn
        by the OS and stays light in dark mode, so Aura never installs one.
        The menu becomes a styled dropdown behind a ☰ button in the header."""
        menu = None
        if isinstance(cnf, dict) and "menu" in cnf:
            menu = cnf.pop("menu")
        if "menu" in kw:
            menu = kw.pop("menu")
        if menu not in (None, ""):
            self.attach_menu(menu)
            if not kw and not cnf:
                return None
        return super().configure(cnf, **kw) if cnf else super().configure(**kw)

    config = configure

    def attach_menu(self, menu):
        """Style *menu* and expose it via a ☰ header button (replaces the
        native menubar)."""
        self._aura_menu = menu
        track(menu, "menu")
        if getattr(self, "_menu_btn", None) is None:
            self._menu_btn = AuraButton(self.header_actions, text="☰",
                                        kind="ghost", width=40,
                                        command=self._post_aura_menu)
            self._menu_btn.pack(side="left", padx=(0, 6))

    def _post_aura_menu(self):
        m = getattr(self, "_aura_menu", None)
        if m is None:
            return
        try:
            style_menu(m)
            x = self._menu_btn.winfo_rootx()
            y = self._menu_btn.winfo_rooty() + self._menu_btn.winfo_height() + 4
            m.tk_popup(x, y)
        finally:
            try:
                m.grab_release()
            except Exception:
                pass

    # ---- live OS-appearance follow ------------------------------------
    def _start_system_listener(self):
        """Re-theme this window when the OS flips Aura Dark/Light.

        ``darkdetect.listener`` blocks on a background daemon thread; the
        callback marshals the change onto the tk main loop via ``after`` so all
        widget work stays on the UI thread.  Entirely best-effort — a desktop
        without a live signal simply follows on next launch instead.
        """
        if darkdetect is None or not hasattr(darkdetect, "listener"):
            return
        import threading

        def _cb(value):
            try:
                t = "dark" if str(value).lower().startswith("d") else "light"
                self.after(0, lambda: self._system_theme_changed(t))
            except Exception:
                pass

        try:
            th = threading.Thread(target=darkdetect.listener, args=(_cb,),
                                  daemon=True)
            th.start()
            self._sys_listener = th
        except Exception:
            self._sys_listener = None

    def _system_theme_changed(self, theme):
        if getattr(self, "_follow_system", False) and theme in ("light", "dark"):
            if theme != self.theme:
                self.set_theme(theme, _system=True)

    def set_theme(self, theme, _system=False):
        if theme not in ("light", "dark"):
            return
        if not _system:
            # an explicit user choice stops OS-follow and becomes the override
            self._follow_system = False
        self.theme = theme
        global _theme
        _theme = theme
        try:
            ctk.set_appearance_mode(theme)
        except Exception:
            pass
        if self._theme_switch.get() != (1 if theme == "dark" else 0):
            (self._theme_switch.select if theme == "dark"
             else self._theme_switch.deselect)()
        style_ttk(self, theme)
        if self._icon_label is not None:
            try:
                self._icon_label.configure(bg=P("surface"))
            except Exception:
                pass
        try:
            self._beam.configure(bg=P("bg"))
        except Exception:
            pass
        self._beam_w = 0
        self._draw_beam()
        windows_polish(self, theme)
        if self.on_theme_change and not _system:
            try:
                self.on_theme_change(theme)
            except Exception:
                pass

    # ---- the signature accent beam ------------------------------------
    def _draw_beam(self, _e=None):
        try:
            w = self._beam.winfo_width()
        except Exception:
            return
        if w <= 1 or w == self._beam_w:
            return
        self._beam_w = w
        self._beam.delete("all")
        p = P()
        accent, bg = p["accent"], p["bg"]
        fade_end = max(1, int(w * 0.85))
        step = 3
        for x in range(0, w, step):
            t = min(1.0, x / fade_end)
            self._beam.create_rectangle(x, 0, x + step, 2,
                                        fill=mix(accent, bg, t), width=0)
